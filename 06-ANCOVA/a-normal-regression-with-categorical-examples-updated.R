# Six illustrative ANCOVA structures (no Stan model is fitted here).
# ANCOVA: illustrating six model structures
set.seed(19)
x1 <- sample(1:100, 20)
x2 <- sample(1:100, 20)
a <- 2 + 3*x1 + rnorm(20, sd = 20)
b <- 3 + 2*x2 + rnorm(20, sd = 20)
y_demo <- c(a, b); x_demo <- c(x1, x2)
group <- rep(1:2, each = 20); d <- as.numeric(group == 2)
par(mfrow = c(2, 3))
plot(x_demo, y_demo, pch = group); abline(h = mean(y_demo)); title("Constant")
plot(x_demo, y_demo, pch = group); abline(lm(y_demo ~ x_demo)); title("Common line")
plot(x_demo, y_demo, pch = group); abline(h = mean(a)); abline(h = mean(b)); title("Group means")
pl <- lm(y_demo ~ x_demo + d)
plot(x_demo, y_demo, pch = group)
abline(coef(pl)[1], coef(pl)[2]); abline(coef(pl)[1]+coef(pl)[3],coef(pl)[2]); title("Parallel")
ci <- lm(y_demo ~ x_demo + I(x_demo*d))
plot(x_demo, y_demo, pch = group)
abline(coef(ci)[1],coef(ci)[2]); abline(coef(ci)[1],coef(ci)[2]+coef(ci)[3]); title("Common intercept")
sl <- lm(y_demo ~ x_demo*d)
plot(x_demo, y_demo, pch = group)
abline(coef(sl)[1],coef(sl)[2]); abline(coef(sl)[1]+coef(sl)[3],coef(sl)[2]+coef(sl)[4]); title("Separate")
par(mfrow = c(1,1))
